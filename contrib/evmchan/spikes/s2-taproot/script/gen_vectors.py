"""Generate test/Vectors.sol from the official BIP340/BIP341 vector files.

Usage: python -I gen_vectors.py bip340-test-vectors.csv bip341-wallet-test-vectors.json > ../test/Vectors.sol

The vector files come from github.com/bitcoin/bips (bip-0340/test-vectors.csv,
bip-0341/wallet-test-vectors.json). Besides transcribing them, this script:
  - computes the R.y hint (even y of lift_x(sig[0:32])) for every signature,
  - recomputes every BIP341 sigHash with an independent Python implementation
    and checks every signature with coincurve (libsecp256k1),
  - makes extra vectors with coincurve: random BIP340 signatures, and signed
    1-input and 2-input P2TR key-path spends for the gas measurements.
"""
import csv
import hashlib
import json
import random
import struct
import sys

from coincurve import PrivateKey, PublicKeyXOnly

P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141


def lift_x_even_y(x):
    """Even y with y^2 = x^3 + 7, or None."""
    if x >= P:
        return None
    c = (pow(x, 3, P) + 7) % P
    y = pow(c, (P + 1) // 4, P)
    if y * y % P != c:
        return None
    return y if y % 2 == 0 else P - y


def ry_hint(sig):
    y = lift_x_even_y(int.from_bytes(sig[:32], "big"))
    return 0 if y is None else y


def sha256(b):
    return hashlib.sha256(b).digest()


def tagged(tag, data):
    t = sha256(tag.encode())
    return sha256(t + t + data)


def cs(n):
    if n < 0xFD:
        return bytes([n])
    if n <= 0xFFFF:
        return b"\xfd" + struct.pack("<H", n)
    if n <= 0xFFFFFFFF:
        return b"\xfe" + struct.pack("<I", n)
    return b"\xff" + struct.pack("<Q", n)


def read_cs(b, o):
    f = b[o]
    if f < 0xFD:
        return f, o + 1
    k = {0xFD: 2, 0xFE: 4, 0xFF: 8}[f]
    return int.from_bytes(b[o + 1:o + 1 + k], "little"), o + 1 + k


def parse_tx(raw):
    """Minimal parser for the unsigned (legacy-format) vector tx."""
    o = 0
    version = struct.unpack_from("<I", raw, o)[0]
    o += 4
    n, o = read_cs(raw, o)
    ins = []
    for _ in range(n):
        txid, vout = raw[o:o + 32], struct.unpack_from("<I", raw, o + 32)[0]
        sl, o = read_cs(raw, o + 36)
        assert sl == 0
        o += sl
        seq = struct.unpack_from("<I", raw, o)[0]
        o += 4
        ins.append((txid, vout, seq))
    n, o = read_cs(raw, o)
    outs = []
    for _ in range(n):
        amt = struct.unpack_from("<Q", raw, o)[0]
        sl, o = read_cs(raw, o + 8)
        outs.append((amt, raw[o:o + sl]))
        o += sl
    locktime = struct.unpack_from("<I", raw, o)[0]
    assert o + 4 == len(raw)
    return version, locktime, ins, outs


def ser_out(amt, spk):
    return struct.pack("<Q", amt) + cs(len(spk)) + spk


def sig_msg(version, locktime, ins, outs, spent, idx, ht):
    """BIP341 SigMsg with the 0x00 epoch prefix, ext_flag 0, no annex."""
    assert ht in (0, 1, 2, 3, 0x81, 0x82, 0x83)
    base, acp = ht & 3, ht & 0x80
    m = bytes([0, ht]) + struct.pack("<II", version, locktime)
    if not acp:
        m += sha256(b"".join(t + struct.pack("<I", v) for t, v, _ in ins))
        m += sha256(b"".join(struct.pack("<Q", a) for a, _ in spent))
        m += sha256(b"".join(cs(len(s)) + s for _, s in spent))
        m += sha256(b"".join(struct.pack("<I", q) for _, _, q in ins))
    if base not in (2, 3):
        m += sha256(b"".join(ser_out(a, s) for a, s in outs))
    m += b"\x00"
    if acp:
        t, v, q = ins[idx]
        a, s = spent[idx]
        m += t + struct.pack("<I", v) + ser_out(a, s) + struct.pack("<I", q)
    else:
        m += struct.pack("<I", idx)
    if base == 3:
        m += sha256(ser_out(*outs[idx]))
    return m


def ser_tx(version, locktime, ins, outs, witnesses=None):
    r = struct.pack("<I", version)
    if witnesses:
        r += b"\x00\x01"
    r += cs(len(ins)) + b"".join(t + struct.pack("<I", v) + b"\x00" + struct.pack("<I", q) for t, v, q in ins)
    r += cs(len(outs)) + b"".join(ser_out(a, s) for a, s in outs)
    if witnesses:
        for w in witnesses:
            r += cs(len(w)) + b"".join(cs(len(i)) + i for i in w)
    return r + struct.pack("<I", locktime)


def xonly(priv):
    return priv.public_key.format(compressed=True)[1:]


def schnorr_ok(pk, msg, sig):
    try:
        return PublicKeyXOnly(pk).verify(sig, msg)
    except Exception:
        return False


def h(b):
    return 'hex"' + b.hex() + '"'


def w(b):
    return "0x" + b.hex()


def main():
    rng = random.Random(340341)
    out = []
    emit = out.append
    emit("// SPDX-License-Identifier: MIT")
    emit("// Generated by script/gen_vectors.py from the official BIP340 and BIP341 test vectors")
    emit("// (github.com/bitcoin/bips) plus extra vectors made with coincurve. Do not edit.")
    emit("pragma solidity ^0.8.24;\n")
    emit('import {TxOut} from "../src/BtcTx.sol";\n')
    emit("struct SchnorrVector { uint256 index; bytes32 pubkey; bytes message; bytes sig; bool ok; uint256 ry; }")
    emit("struct KeyPathInput { uint256 index; uint8 hashType; bytes sigMsg; bytes32 sigHash; bytes sig; uint256 ry; }")
    emit("struct SignedSpend { bytes rawTx; TxOut[] spent; uint256[] ry; }\n")
    emit("library Vectors {")

    # BIP340 official vectors
    rows = list(csv.DictReader(open(sys.argv[1], newline="")))
    emit(f"    uint256 internal constant BIP340_COUNT = {len(rows)};\n")
    emit("    function bip340(uint256 i) internal pure returns (SchnorrVector memory v) {")
    for r in rows:
        pk, msg, sig = (bytes.fromhex(r[k]) for k in ("public key", "message", "signature"))
        ok = r["verification result"] == "TRUE"
        assert schnorr_ok(pk, msg, sig) == ok, r["index"]
        emit(f'        if (i == {r["index"]}) return SchnorrVector({r["index"]}, {w(pk)}, {h(msg)}, {h(sig)}, {str(ok).lower()}, {ry_hint(sig)});')
    emit('        revert("no such vector");\n    }\n')

    # Random extra BIP340 vectors (32-byte messages), checked with coincurve
    extra = []
    for _ in range(32):
        k = PrivateKey(rng.randbytes(32))
        msg = rng.randbytes(32)
        sig = k.sign_schnorr(msg, rng.randbytes(32))
        assert schnorr_ok(xonly(k), msg, sig)
        extra.append((xonly(k), msg, sig))
    emit(f"    uint256 internal constant RANDOM_COUNT = {len(extra)};\n")
    emit("    function random(uint256 i) internal pure returns (SchnorrVector memory v) {")
    for i, (pk, msg, sig) in enumerate(extra):
        emit(f"        if (i == {i}) return SchnorrVector({i}, {w(pk)}, {h(msg)}, {h(sig)}, true, {ry_hint(sig)});")
    emit('        revert("no such vector");\n    }\n')

    # BIP341 key path vectors
    kp = json.load(open(sys.argv[2]))["keyPathSpending"]
    assert len(kp) == 1
    kp = kp[0]
    raw = bytes.fromhex(kp["given"]["rawUnsignedTx"])
    version, locktime, ins, outs = parse_tx(raw)
    spent = [(u["amountSats"], bytes.fromhex(u["scriptPubKey"])) for u in kp["given"]["utxosSpent"]]
    emit(f"    bytes internal constant BIP341_RAW_UNSIGNED_TX = {h(raw)};")
    emit(f'    bytes internal constant BIP341_FULLY_SIGNED_TX = {h(bytes.fromhex(kp["auxiliary"]["fullySignedTx"]))};')
    im = kp["intermediary"]
    for k in ("hashAmounts", "hashOutputs", "hashPrevouts", "hashScriptPubkeys", "hashSequences"):
        emit(f"    bytes32 internal constant BIP341_{k.upper()} = {w(bytes.fromhex(im[k]))};")
    emit("")
    emit("    function bip341Spent() internal pure returns (TxOut[] memory s) {")
    emit(f"        s = new TxOut[]({len(spent)});")
    for i, (a, spk) in enumerate(spent):
        emit(f"        s[{i}] = TxOut({a}, {h(spk)});")
    emit("    }\n")
    inputs = kp["inputSpending"]
    emit(f"    uint256 internal constant BIP341_INPUT_COUNT = {len(inputs)};\n")
    emit("    function bip341Input(uint256 i) internal pure returns (KeyPathInput memory v) {")
    for j, inp in enumerate(inputs):
        g, it = inp["given"], inp["intermediary"]
        idx, ht = g["txinIndex"], g["hashType"]
        m = sig_msg(version, locktime, ins, outs, spent, idx, ht)
        assert m.hex() == it["sigMsg"], idx
        sh = tagged("TapSighash", m)
        assert sh.hex() == it["sigHash"], idx
        sig = bytes.fromhex(inp["expected"]["witness"][0])
        assert len(inp["expected"]["witness"]) == 1
        assert (len(sig) == 64 and ht == 0) or (len(sig) == 65 and sig[64] == ht)
        assert schnorr_ok(spent[idx][1][2:], sh, sig[:64])
        emit(f"        if (i == {j}) return KeyPathInput({idx}, {ht}, {h(m)}, {w(sh)}, {h(sig)}, {ry_hint(sig)});")
    emit('        revert("no such vector");\n    }\n')

    # Signed spends for the gas measurements: n P2TR inputs, 2 P2TR outputs, DEFAULT sigs
    for n_in in (1, 2):
        keys = [PrivateKey(rng.randbytes(32)) for _ in range(n_in)]
        spent2 = [(rng.randrange(100_000, 10_000_000), b"\x51\x20" + xonly(k)) for k in keys]
        ins2 = [(rng.randbytes(32), rng.randrange(0, 4), 0xFFFFFFFD) for _ in range(n_in)]
        total = sum(a for a, _ in spent2)
        outs2 = [(total // 3, b"\x51\x20" + rng.randbytes(32)), (total - total // 3 - 500, b"\x51\x20" + rng.randbytes(32))]
        ver2, lt2 = 2, 850_000
        wit = []
        hints = []
        for i, k in enumerate(keys):
            sh = tagged("TapSighash", sig_msg(ver2, lt2, ins2, outs2, spent2, i, 0))
            sig = k.sign_schnorr(sh, rng.randbytes(32))
            assert schnorr_ok(xonly(k), sh, sig)
            wit.append([sig])
            hints.append(ry_hint(sig))
        signed = ser_tx(ver2, lt2, ins2, outs2, wit)
        emit(f"    function spend{n_in}In() internal pure returns (SignedSpend memory s) {{")
        emit(f"        s.rawTx = {h(signed)};")
        emit(f"        s.spent = new TxOut[]({n_in});")
        emit(f"        s.ry = new uint256[]({n_in});")
        for i, (a, spk) in enumerate(spent2):
            emit(f"        s.spent[{i}] = TxOut({a}, {h(spk)});")
            emit(f"        s.ry[{i}] = {hints[i]};")
        emit("    }\n")
        txid = sha256(sha256(ser_tx(ver2, lt2, ins2, outs2)))
        emit(f"    bytes32 internal constant SPEND{n_in}_TXID = {w(txid)};\n")

    emit("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
